def fragment(*, pre: str | None = VECTOR_LINE, timeout: str | None = "TimeoutStartSec=90", start: str | None = "ExecStart=/bin/true",
             extra: str = "", install: str = "", marker: bool = True, note: str = "") -> bytes:
    """A synthetic fragment: every piece the installer judges can be altered or dropped."""
    lines = [tool.MARKER.decode().rstrip("\n")] if marker else []
    lines += ["[Unit]", f"Description=synthetic capture unit {note}", "[Service]", "Type=exec"]
    lines += [item for item in (pre, start, timeout) if item is not None]
    return ("\n".join(lines) + "\n" + extra + install).encode()


def show_span(seconds: float) -> str:
    """How systemd prints a timespan: ``90s`` -> ``1min 30s``, ``1h`` -> ``1h``, ``500ms`` -> ``500ms``."""
    if seconds < 1:
        return f"{round(seconds * 1000)}ms"
    parts, rest = [], round(seconds, 3)
    for name, size in (("h", 3600), ("min", 60)):
        if rest >= size:
            parts.append(f"{int(rest // size)}{name}")
            rest -= int(rest // size) * size
    if rest:
        parts.append(f"{rest:g}s")
    return " ".join(parts)


class World:
    """A re-rooted filesystem and a stateful model of the system manager."""

    def __init__(self, tmp_path: Path) -> None:
        self.root = tmp_path / "root"
        self.calls: list[list[str]] = []
        self.events: list[str] = []
        self.state = "inactive"
        self.loaded: bytes | None = None
        self.dropins = ""
        self.unit_file_state = "static"
        self.properties: dict[str, str] = {}
        self.exec_pre: list[str] | None = None  # an explicit ExecStartPreEx read-back (overrides the one derived from ``loaded``)
        self.timeout_shown: str | None = None
        self.reload_results: list[int] = []
        self.reload_noop = False
        self.after_reload = None
        self.faults: list[tuple[str, int, BaseException]] = []
        self.state_faults: list[str] = []
        self.verb_calls: dict[str, int] = {}
        for rel in ("etc/systemd/system", "run/systemd/system", "usr/bin", "usr/local/libexec/freedom-blades-rp11/sub", "infra/rp11"):
            (self.root / rel).mkdir(parents=True)
        (self.root / ROLE_ARTIFACT.lstrip("/")).write_text("#artifact")
        (self.root / ROLE_ARTIFACT.lstrip("/")).with_name("sub").joinpath("inner.py").write_text("#inner")
        (self.root / ROLE_INTERPRETER.lstrip("/")).write_text("#interpreter")
        self.repo = self.root / "repo"
        (self.repo / "infra/rp11").mkdir(parents=True)
        for path in [*self.root.rglob("*"), self.root]:
            path.chmod(0o755 if path.is_dir() else 0o644)
        self.write_source(fragment())

    # --- files ----------------------------------------------------------------------------------------

    def write_source(self, data: bytes) -> None:
        path = self.repo / SOURCE
        path.unlink(missing_ok=True)
        path.write_bytes(data)
        path.chmod(0o644)

    @property
    def fragment_path(self) -> Path:
        return self.root / "etc/systemd/system" / UNIT

    def disk(self) -> bytes | None:
        return self.fragment_path.read_bytes() if self.fragment_path.exists() else None

    def put(self, data: bytes, *, mode: int = 0o644) -> None:
        self.fragment_path.write_bytes(data)
        self.fragment_path.chmod(mode)

    def install_loaded(self, data: bytes) -> None:
        """A state the host could already be in: fragment on disk and loaded."""
        self.put(data)
        self.loaded = data

    # --- the manager ------------------------------------------------------------------------------------

    def runner(self, argv):
        self.calls.append(list(argv))
        if argv[0] == "systemctl":
            return self._systemctl(argv[1:])
        return 0, ""

    def _derived(self) -> tuple[list[str], str]:
        """What the manager would print for ExecStartPreEx and TimeoutStartUSec from the fragment it has loaded."""
        entries, timeout = [], "infinity"
        for line in (self.loaded or b"").decode().splitlines():
            if line.startswith("ExecStartPre="):
                value = line.removeprefix("ExecStartPre=")
                flags = "privileged" if value.startswith("+") else ""
                argv = value.lstrip("+-@:!")
                entries.append(f"{{ path={argv.split()[0]} ; argv[]={argv} ; flags={flags} ; start_time=[n/a] ; pid=0 ; status=0/0 }}")
            if line.startswith("TimeoutStartSec="):
                value = line.removeprefix("TimeoutStartSec=")
                found = re.fullmatch(r"([0-9.]+)([a-z]*)", value)
                factor = {"": 1, "s": 1, "ms": 0.001, "min": 60, "h": 3600}.get(found[2]) if found else None
                timeout = show_span(float(found[1]) * factor) if factor else "infinity"
        return entries, timeout

    def _systemctl(self, args):
        verb = args[0]
        self.verb_calls[verb] = self.verb_calls.get(verb, 0) + 1
        for fault in self.faults:
            if fault[0] == verb and fault[1] == self.verb_calls[verb]:
                self.faults.remove(fault)
                raise fault[2]
        if verb == "show":
            wanted = [item[2:] for item in args[2:] if item.startswith("-p")]
            if wanted == ["ActiveState"] and self.state_faults:
                mode = self.state_faults.pop(0)
                if mode == "fail":
                    return 1, ""
                return 0, {"empty": "ActiveState=\n", "garbage": "ActiveState=bogus\n", "missing": ""}[mode]
            entries, timeout = self._derived()
            values = {"ActiveState": self.state, "LoadState": "loaded" if self.loaded is not None else "not-found",
                      "FragmentPath": f"/etc/systemd/system/{UNIT}" if self.loaded is not None else "",
                      "NeedDaemonReload": "no" if self.disk() == self.loaded else "yes", "DropInPaths": self.dropins,
                      "UnitFileState": self.unit_file_state if self.loaded is not None else "",
                      "TimeoutStartUSec": self.timeout_shown or timeout, **self.properties}
            lines = []
            for name in wanted:
                if name == "ExecStartPreEx":
                    lines += [f"ExecStartPreEx={item}" for item in (self.exec_pre if self.exec_pre is not None else entries)]
                elif name in values:
                    lines.append(f"{name}={values[name]}")
            return 0, "".join(line + "\n" for line in lines)
        if verb == "daemon-reload":
            self.events.append("reload")
            code = self.reload_results.pop(0) if self.reload_results else 0
            if code == 0 and not self.reload_noop:
                self.loaded = self.disk()
            if self.after_reload is not None:
                self.after_reload()
            return code, ""
        self.events.append(verb)  # enable/disable/start/stop/...: tests assert this installer never issues them
        return 0, ""


@pytest.fixture
def world(tmp_path):
    return World(tmp_path)


def make(world: World, *, spec: UnitSpec = SPEC, euid: int = ME, **kw) -> Installer:
    return Installer(world.repo, spec=spec, root=str(world.root), run=world.runner, euid=lambda: euid,
                     trusted=(ME, os.getgid()), **kw)


def expect(callable_, code: int, word: str) -> Failure:
    with pytest.raises(Failure) as caught:
        callable_()
    assert (caught.value.code, caught.value.word) == (code, word), (caught.value.code, caught.value.word)
    return caught.value


def untouched(world: World) -> None:
    assert world.disk() is None and world.loaded is None
    assert not [p for p in (world.root / "etc/systemd/system").iterdir()]


