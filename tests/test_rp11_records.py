WRONG_VALUES = [None, 0, 7, -1, True, False, 1.5, "", "\x00bad", "X" * 300, [], {}, ["x"], {"x": 1}]
SAMPLES = ["act-activated", "act-failed", "deact-verified", "deact-hard-stop", "deact-hard-stop-residual"]


def walk(value, path=()):
    yield path, value
    if type(value) is dict:
        for key, item in value.items():
            yield from walk(item, (*path, key))
    elif type(value) is list:
        for index, item in enumerate(value):
            yield from walk(item, (*path, index))


def get_at(doc, path):
    for step in path:
        doc = doc[step]
    return doc


def replaced(doc, path, new):
    if not path:
        return new
    clone = copy.deepcopy(doc)
    get_at(clone, path[:-1])[path[-1]] = new
    return clone


def deletions(doc):
    for path, value in walk(doc):
        if type(value) is dict:
            for key in value:
                clone = copy.deepcopy(doc)
                del get_at(clone, path)[key]
                yield (*path, key), "delete", clone


def additions(doc):
    for path, value in walk(doc):
        if type(value) is dict:
            clone = copy.deepcopy(doc)
            get_at(clone, path)["zz_extra"] = 1
            yield path, "extra key", clone


def type_swaps(doc):
    for path, value in walk(doc):
        for new in WRONG_VALUES:
            if type(new) is not type(value):
                yield path, f"{type(value).__name__} -> {new!r}"[:60], replaced(doc, path, new)


def assert_rejected(mutated, what: str, failures: list[str]) -> None:
    try:
        validate_record(mutated)
    except RecordSchemaError:
        pass
    except BaseException as exc:  # noqa: BLE001 - the point: nothing else may escape
        failures.append(f"{what}: validate leaked {type(exc).__name__}: {exc}")
        return
    else:
        failures.append(f"{what}: accepted")
        return
    try:
        branch = branch_for_record(wire(mutated), activation_id=ACT_ID, k=attempt_of(mutated))
    except BaseException as exc:  # noqa: BLE001
        failures.append(f"{what}: branch_for_record leaked {type(exc).__name__}")
        return
    if branch is not Branch.BS4:
        failures.append(f"{what}: selected {branch.value}")


@pytest.mark.parametrize("name", SAMPLES)
@pytest.mark.parametrize("family", [deletions, additions, type_swaps], ids=lambda f: f.__name__)
def test_every_nested_mutation_raises_only_record_schema_error_and_selects_bs4(samples, name, family):
    base = doc_of(samples, name)
    failures: list[str] = []
    count = 0
    for path, what, mutated in family(base):
        count += 1
        assert_rejected(mutated, f"{name} {'.'.join(map(str, path))} {what}", failures)
    assert count > 25
    assert failures == [], f"{len(failures)} of {count}: " + "; ".join(failures[:12])


