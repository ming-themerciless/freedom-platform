"""The reusable RP-11 capture-unit installer, exercised **only with synthetic unit fragments**.

No production fragment exists or is created here: every fragment is generated by this module, under a throwaway unit
name, in a re-rooted filesystem against a *stateful* model of the system manager (what it has loaded, what ``show``
reports, ``NeedDaemonReload`` derived from the difference), so an install that does not reload, or whose reload is a
no-op, cannot look successful. Nothing here invents a production ``ExecStart``, sandbox set or timeout duration: those
are inputs the tests vary.
"""

