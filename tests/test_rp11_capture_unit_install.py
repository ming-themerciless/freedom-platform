def test_the_source_must_be_a_root_owned_link_free_non_writable_single_link_file(world):
    path = world.repo / SOURCE
    path.chmod(0o664)
    expect(make(world).install, EXIT_REFUSED, "code-writable")  # judged first, with every object on the path to it
    path.chmod(0o644)
    os.link(path, world.repo / "alias")
    expect(make(world).install, EXIT_REFUSED, "source-invalid")
    (world.repo / "alias").unlink()
    data = path.read_bytes()
    path.unlink()
    (world.repo / "real").write_bytes(data)
    path.symlink_to("../../real")
    expect(make(world).install, EXIT_REFUSED, "code-symlink")
    path.unlink()
    path.write_bytes(data + b"#" * 9000)
    path.chmod(0o644)
    expect(make(world).install, EXIT_REFUSED, "source-invalid")
    untouched(world)


