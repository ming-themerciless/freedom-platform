def doc_of(samples, name: str) -> dict:
    return copy.deepcopy(samples[name])


def wire(doc: object) -> bytes:
    """The bytes a record store would hand the backstop (JSON as written, final LF)."""
    return (json.dumps(doc, sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n").encode("ascii")


def attempt_of(doc: object) -> int:
    return doc["attempt"] if type(doc) is dict and type(doc.get("attempt")) is int else 1


