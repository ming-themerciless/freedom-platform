def run_main(world: World, action: str, capsys, **kw) -> tuple[int, str, str]:
    code = main([action], installer=make(world, **kw))
    out = capsys.readouterr()
    return code, out.out, out.err


def test_statuses_and_fixed_diagnostic_words(world, capsys):
    assert run_main(world, "verify", capsys) == (EXIT_VERIFY_FAILED, "", "rp11-capture-unit not-installed\n")
    assert run_main(world, "install", capsys) == (EXIT_OK, "rp11-capture-unit installed\n", "")
    assert run_main(world, "verify", capsys) == (EXIT_OK, "rp11-capture-unit installed\n", "")
    world.state = "active"
    world.loaded = None
    assert run_main(world, "install", capsys)[::2] == (EXIT_PENDING, "rp11-capture-unit capture-active\n")
    world.state = "inactive"
    assert run_main(world, "remove", capsys) == (EXIT_OK, "rp11-capture-unit removed\n", "")
    world.reload_results = [1, 1]
    assert run_main(world, "install", capsys)[::2] == (EXIT_RECOVERY, "rp11-capture-unit recovery-incomplete\n")
    world.reload_results = []
    (world.root / "run/systemd/system" / UNIT).write_text("")
    assert run_main(world, "install", capsys)[::2] == (EXIT_CONFLICT, "rp11-capture-unit shadowed\n")
    assert run_main(world, "install", capsys, euid=ME + 1)[::2] == (EXIT_REFUSED, "rp11-capture-unit not-root\n")


