"""The reusable capture-unit installer against the **real system manager** on the disposable host, with a synthetic unit only.

Everything here is throwaway: a randomly named ``rp11-capture-synthetic-<token>.service`` fragment generated by this
module under a root-owned scratch directory in ``/srv``, and (only if absent) a synthetic, **never executed** stand-in at
the fixed artifact path so that the installer's trust chain has something real to judge. The unit is never started,
enabled or linked, so nothing runs the consume role and no RP-11 capture pass, activation, grant or evidence exists.
Nothing production-shaped is installed: ``rp11-capture-pass-a.service`` is never written. Synthetic data only.

    sudo env FREEDOM_SYSTEMD_INTEGRATION=oracle-test \\
        /opt/freedom-blades/runtime/venv-web/bin/python -B -m pytest -q -rfEs \\
        tests/systemd_integration/test_rp11_capture_unit_install_host.py

Teardown removes only what this module created, by exact name and identity (``synthetic_cleanup``): never a recursive
delete, never a shared parent such as ``/usr/local/libexec`` except by ``rmdir`` of an empty directory this run made.
Unexpected residue makes the teardown fail and is left in place. It asserts the fragment, the scratch directory and the
stand-in tree are gone and that the manager no longer knows the unit.
"""

from __future__ import annotations

import os
import secrets
import stat
from pathlib import Path

import pytest

import test_route3_hold_host as hold_host  # noqa: F401  (applies the same disposable-host guards)
from synthetic_cleanup import Ledger, remove_file_exact
from test_route3_hold_host import run, show

from adapters.systemd.manager import ROLE_ARTIFACT
from tools import rp11_capture_unit_install as tool
from tools.executor_supervisor_install import EXIT_CONFLICT, EXIT_IO, EXIT_PENDING, EXIT_VERIFY_FAILED, Failure
from tools.rp11_capture_unit_install import CONSUME_VECTOR, Installer, UnitSpec

TOKEN = secrets.token_hex(3)
UNIT = f"rp11-capture-synthetic-{TOKEN}.service"
SOURCE = Path("infra/rp11") / UNIT
SCRATCH = Path(f"/srv/fbcap-{TOKEN}")
LIBEXEC = Path(ROLE_ARTIFACT).parent
UNIT_FILE = Path("/etc/systemd/system") / UNIT
#: Inputs a reviewed production spec would supply; synthetic here, chosen only because the real manager reports them.
SPEC = UnitSpec(unit=UNIT, source_relative=SOURCE, required_directives=("NoNewPrivileges=yes", "PrivateTmp=yes"),
                required_properties={"NoNewPrivileges": "yes", "PrivateTmp": "yes"}, max_start_timeout_seconds=3600)


def fragment(note: str = "synthetic", *, extra: str = "") -> bytes:
    return (
        f"{tool.MARKER.decode()}[Unit]\nDescription=synthetic capture unit {note}\n[Service]\nType=exec\n"
        f"ExecStartPre=+{' '.join(CONSUME_VECTOR)}\nExecStart=/usr/bin/sleep 600\nTimeoutStartSec=90\n"
        f"NoNewPrivileges=yes\nPrivateTmp=yes\n{extra}"
    ).encode()


def state() -> dict[str, str]:
    return show(UNIT, "LoadState", "ActiveState", "FragmentPath", "UnitFileState", "DropInPaths", "NeedDaemonReload", "InvocationID",
                "Description")


def installer(source: bytes | None = None, *, spec: UnitSpec = SPEC, runner=None) -> Installer:
    if source is not None:
        LEDGER.replace(SCRATCH / SOURCE, source, 0o644)
    kwargs = {"run": runner} if runner is not None else {}
    return Installer(SCRATCH, spec=spec, **kwargs)


def reload_real(argv):
    return tool._run(argv)


STAND_IN = b"# synthetic stand-in; never executed (the capture unit is never started)\n"
FOREIGN_UNIT = b"[Service]\nExecStart=/bin/false\n"
DROP_IN = UNIT_FILE.with_name(UNIT + ".d")
DROP_IN_BODY = b"[Service]\nNoNewPrivileges=no\n"
LEDGER = Ledger()  # every directory and file this module created, identity recorded at creation


def plant_drop_in() -> None:
    """Create the override directory and file; both identities are recorded per instance, at creation."""
    LEDGER.mkdir(DROP_IN)
    LEDGER.write(DROP_IN / "override.conf", DROP_IN_BODY)


def remove_drop_in() -> None:
    """Remove the override this module planted (recorded identity and exact body); anything else stays and fails."""
    LEDGER.remove_dir(DROP_IN)


def remove_unit_file() -> None:
    """Remove the unit file only if it is the recorded planted file, or a single-link regular file the installer wrote
    (marker prefix; the unit name is random per run). Anything else is refused and left in place."""
    if UNIT_FILE in LEDGER:
        LEDGER.remove_file(UNIT_FILE)
    else:
        remove_file_exact(UNIT_FILE, prefix=tool.MARKER)


def _run_cleanups() -> list[str]:
    problems: list[str] = []
    for cleanup in (remove_unit_file, remove_drop_in):
        try:
            cleanup()
        except (AssertionError, OSError) as error:
            problems.append(str(error))
    return problems


@pytest.fixture(scope="module", autouse=True)
def synthetic_host():
    """The scratch tree and (only if absent) the stand-in artifact, with a before/after residue comparison.

    Every directory and file is recorded at creation (``Ledger``). Teardown never recurses and never unlinks blindly: it
    removes exactly the recorded objects after proving type, link count, identity and bytes, and uses ``rmdir`` only. The
    shared ``/usr/local/libexec`` parent is removed only if this run created it; any unexpected or replaced state fails
    the run and is left in place.
    """
    assert not os.path.lexists(UNIT_FILE) and not os.path.lexists(SCRATCH), "a previous run left synthetic state"
    for decoy in ("rp11-capture-pass-a.service",):  # the production name must be untouched by this module
        assert not (Path("/etc/systemd/system") / decoy).exists(), "refusing: a production-named capture unit exists on this host"
    if LIBEXEC.exists():
        pytest.skip("the fixed RP-11 artifact tree is present on this host: refusing to alter it")
    made_libexec = not LIBEXEC.parent.exists()
    before_wants = sorted(p.name for p in Path("/etc/systemd/system").iterdir())
    try:
        for directory in (SCRATCH, SCRATCH / "infra", SCRATCH / "infra/rp11"):
            LEDGER.mkdir(directory)
        if made_libexec:
            LEDGER.mkdir(LIBEXEC.parent)
        LEDGER.mkdir(LIBEXEC)
        LEDGER.write(Path(ROLE_ARTIFACT), STAND_IN)
        yield
    finally:
        run("systemctl", "stop", UNIT)  # only ever a no-op; the unit is never started
        problems = _run_cleanups()
        run("systemctl", "daemon-reload")
        problems.extend(LEDGER.remove_all())
        assert not problems, "teardown refused to delete unexpected state: " + "; ".join(problems)
    assert not UNIT_FILE.exists() and not SCRATCH.exists() and not LIBEXEC.exists()
    assert not LIBEXEC.parent.exists() or not made_libexec
    assert sorted(p.name for p in Path("/etc/systemd/system").iterdir()) == before_wants
    assert state()["LoadState"] == "not-found"


@pytest.fixture(autouse=True)
def clean_unit():
    yield
    problems = _run_cleanups()
    run("systemctl", "daemon-reload")
    assert not problems, "cleanup refused to delete unexpected state: " + "; ".join(problems)
    assert state()["LoadState"] == "not-found"


def test_install_verify_and_remove_against_the_real_manager_never_start_or_enable_the_unit():
    tool_ = installer(fragment())
    assert tool_.install() == "installed"
    shown = state()
    assert shown["LoadState"] == "loaded" and shown["FragmentPath"] == str(UNIT_FILE)
    assert shown["UnitFileState"] == "static" and shown["DropInPaths"] == "" and shown["NeedDaemonReload"] == "no"
    assert shown["ActiveState"] == "inactive" and shown["InvocationID"] == ""  # never started: no invocation exists
    info = UNIT_FILE.stat()
    assert (info.st_uid, info.st_gid, stat.S_IMODE(info.st_mode), info.st_nlink) == (0, 0, 0o644, 1)
    assert not [p for p in Path("/etc/systemd/system").glob(f".{UNIT}*")]
    assert not list(Path("/etc/systemd/system").glob(f"*.wants/{UNIT}")) and not list(Path("/etc/systemd/system").glob(f"*.requires/{UNIT}"))
    # The manager's own read-back of the approved consume step, in the form this systemd prints it.
    pre = run("systemctl", "show", UNIT, "-pExecStartPreEx").stdout.strip().splitlines()
    assert len(pre) == 1 and f"path={CONSUME_VECTOR[0]} ;" in pre[0] and f"argv[]={' '.join(CONSUME_VECTOR)} ;" in pre[0]
    assert "flags=privileged ;" in pre[0], pre
    assert tool_.install() == "installed" and tool_.verify() == "installed"
    assert tool_.remove() == "removed"
    assert not UNIT_FILE.exists() and state()["LoadState"] == "not-found"
    assert tool_.remove() == "removed"


def test_an_upgrade_replaces_the_marked_fragment_and_the_manager_loads_the_new_one():
    installer(fragment("first")).install()
    assert state()["Description"].endswith("first")
    assert installer(fragment("second")).install() == "installed"
    assert state()["Description"].endswith("second") and state()["NeedDaemonReload"] == "no"
    with pytest.raises(Failure) as caught:  # the old revision is not "installed" any longer
        installer(fragment("first")).verify()
    assert (caught.value.code, caught.value.word) == (EXIT_VERIFY_FAILED, "not-installed")


def test_a_foreign_fragment_a_shadow_and_a_drop_in_are_refused_and_left_untouched():
    LEDGER.write(UNIT_FILE, FOREIGN_UNIT, 0o644)  # identity recorded at creation
    with pytest.raises(Failure) as caught:
        installer(fragment()).install()
    assert (caught.value.code, caught.value.word) == (EXIT_CONFLICT, "destination-conflict")
    assert UNIT_FILE.read_bytes() == FOREIGN_UNIT
    LEDGER.remove_file(UNIT_FILE)
    plant_drop_in()
    with pytest.raises(Failure) as caught:
        installer(fragment()).install()
    assert (caught.value.code, caught.value.word) == (EXIT_CONFLICT, "shadowed") and not UNIT_FILE.exists()


def test_a_drop_in_that_the_real_manager_reports_after_the_reload_fails_the_install_and_withdraws_the_fragment():
    drop_in = DROP_IN

    def runner(argv):
        if argv[:2] == ["systemctl", "daemon-reload"] and not drop_in.exists():
            plant_drop_in()  # an override that appears between the placement and the manager's load of it
        return reload_real(argv)

    with pytest.raises(Failure) as caught:
        installer(fragment(), runner=runner).install()
    # The first reload loads the override (read-back refused); the withdrawal's own reload still sees it, so the
    # outcome is the honest "could not prove the manager forgot the unit"; once the override is gone it is clean.
    assert caught.value.word in ("reload-failed", "recovery-incomplete")
    remove_drop_in()
    run("systemctl", "daemon-reload")
    assert not UNIT_FILE.exists() and state()["LoadState"] == "not-found"


def test_a_failed_first_reload_is_withdrawn_and_the_real_manager_proves_it_forgot_the_unit():
    seen = {"n": 0}

    def runner(argv):
        if argv[:2] == ["systemctl", "daemon-reload"]:
            seen["n"] += 1
            if seen["n"] == 1:
                return 1, ""  # the manager "failed": it loaded nothing
        return reload_real(argv)

    with pytest.raises(Failure) as caught:
        installer(fragment(), runner=runner).install()
    assert (caught.value.code, caught.value.word) == (EXIT_IO, "reload-failed")
    assert not UNIT_FILE.exists() and state()["LoadState"] == "not-found" and seen["n"] == 2


def test_a_failed_upgrade_restores_the_earlier_fragment_in_the_real_manager():
    installer(fragment("first")).install()
    seen = {"n": 0}

    def runner(argv):
        if argv[:2] == ["systemctl", "daemon-reload"]:
            seen["n"] += 1
            if seen["n"] == 1:
                return 1, ""
        return reload_real(argv)

    with pytest.raises(Failure) as caught:
        installer(fragment("second"), runner=runner).install()
    assert (caught.value.code, caught.value.word) == (EXIT_IO, "reload-failed")
    assert UNIT_FILE.read_bytes() == fragment("first") and state()["Description"].endswith("first")
    assert state()["NeedDaemonReload"] == "no" and state()["ActiveState"] == "inactive"


def test_a_removal_whose_reload_fails_puts_the_fragment_back_and_the_manager_holds_it_again():
    installer(fragment("kept")).install()
    seen = {"n": 0}

    def runner(argv):
        if argv[:2] == ["systemctl", "daemon-reload"]:
            seen["n"] += 1
            if seen["n"] == 1:
                return 1, ""
        return reload_real(argv)

    with pytest.raises(Failure) as caught:
        installer(runner=runner).remove()
    assert (caught.value.code, caught.value.word) == (EXIT_IO, "reload-failed")
    assert UNIT_FILE.read_bytes() == fragment("kept") and state()["LoadState"] == "loaded" and state()["NeedDaemonReload"] == "no"


def test_a_sandbox_requirement_the_fragment_lacks_or_the_manager_does_not_report_refuses():
    weaker = fragment().replace(b"PrivateTmp=yes\n", b"")
    with pytest.raises(Failure) as caught:
        installer(weaker).install()
    assert caught.value.word == "fragment-directive" and not UNIT_FILE.exists()
    stricter = UnitSpec(unit=UNIT, source_relative=SOURCE, required_properties={"ProtectSystem": "strict"})
    with pytest.raises(Failure) as caught:
        installer(fragment(), spec=stricter).install()  # the fragment is valid; the manager does not report ProtectSystem=strict
    assert caught.value.word == "reload-failed" and not UNIT_FILE.exists() and state()["LoadState"] == "not-found"


def test_a_capture_unit_that_is_not_idle_is_never_replaced_or_removed():
    installer(fragment("first")).install()

    def runner(argv):
        if argv[:2] == ["systemctl", "show"] and argv[-1] == "-pActiveState":
            return 0, "ActiveState=activating\n"  # the manager is told only what a start in progress would report
        return reload_real(argv)

    for action in ("install", "remove"):
        with pytest.raises(Failure) as caught:
            getattr(installer(fragment("second"), runner=runner), action)()
        assert (caught.value.code, caught.value.word) == (EXIT_PENDING, "capture-active")
    assert UNIT_FILE.read_bytes() == fragment("first") and state()["ActiveState"] == "inactive"
