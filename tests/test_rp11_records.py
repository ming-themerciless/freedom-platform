CLEANUP_SAMPLES = ["act-failed", "deact-verified", "deact-hard-stop", "deact-hard-stop-residual"]
CLAIMS = ["not-authorized", "unconfirmed", "authorized", ABSENT]


def _claim(doc: dict, after: str, outcome: str) -> None:
    doc["grant_check"]["after_cleanup"] = after
    doc["pk"]["outcome"] = outcome


@pytest.mark.parametrize("name", CLEANUP_SAMPLES)
@pytest.mark.parametrize("after", CLAIMS)
@pytest.mark.parametrize("outcome", CLAIMS)
def test_every_unequal_pair_of_after_cleanup_and_pk_outcome_is_rejected(samples, name, after, outcome):
    doc = doc_of(samples, name)
    if after == outcome == doc["pk"]["outcome"]:
        validate_record(doc)
        return
    _claim(doc, after, outcome)
    if after == outcome:
        return  # equal pairs are judged by the other relations (mode, reason, checks), below
    with pytest.raises(RecordSchemaError):
        validate_record(doc)
    assert branch_for_record(wire(doc), activation_id=ACT_ID, k=attempt_of(doc)) is Branch.BS4


