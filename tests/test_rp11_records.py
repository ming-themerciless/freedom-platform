@pytest.mark.parametrize(
    "path,make",
    [
        ((), _Dict),
        (("pk",), _Dict),
        (("outcome",), _Str),
        (("activation_id",), _Str),
        (("attempt",), _Int),
        (("st1", "checks"), _Dict),
        (("directories",), lambda v: type("L", (list,), {})(v)),
        (("directories", 0), _Dict),
        (("st1", "verified"), _Int),
        (("pk", "calls"), lambda v: True),
    ],
)
def test_subclasses_and_booleans_are_not_exact_types(samples, path, make):
    doc = doc_of(samples, "deact-verified")
    if path == ("directories", 0) and not doc["directories"]:
        pytest.skip("no directory entry")
    node = get_at(doc, path)
    mutated = replaced(doc, path, make(node))
    with pytest.raises(RecordSchemaError):
        validate_record(mutated)
    # a subclass does not survive serialization; only a boolean in an integer's place does
    if type(get_at(mutated, path)) is bool:
        assert branch_for_record(wire(mutated), activation_id=ACT_ID, k=1) is Branch.BS4


