"""``rp11-activation-record/2``: the total validator and the backstop's use of it.

Four record shapes are generated by the real procedures (the hold's ``activated``
ACT record, CL-7's ``failed`` ACT record, a ``st1-verified`` and a ``hard-stop``
deactivation record). Every nested field of each is then mutated systematically:
deleted, given an extra sibling, and replaced by each wrong type, plus a table of
bounds and a table of cross-field contradictions. ``validate_record`` must raise
``RecordSchemaError`` and nothing else for every mutation, and ``branch_for_record``
must select BS-4 for every one of them without raising.
"""

