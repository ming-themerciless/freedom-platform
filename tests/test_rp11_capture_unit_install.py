def test_install_places_the_fragment_once_and_reloads_without_enabling_starting_or_stopping(world):
    installer = make(world)
    assert installer.install() == "installed"
    assert world.disk() == (world.repo / SOURCE).read_bytes()
    assert oct(world.fragment_path.stat().st_mode & 0o777) == "0o644"
    assert world.loaded == world.disk()  # the manager demonstrably holds exactly the installed fragment
    assert world.events == ["reload"] and ["systemctl", "daemon-reload"] in world.calls
    assert not list((world.root / "etc/systemd/system").glob(".*"))  # no temporary alias left behind
    assert installer.install() == "installed" and world.events == ["reload"]  # idempotent: no rewrite, no second reload
    assert installer.verify() == "installed"
    assert not any(c[:2] == ["systemctl", verb] for c in world.calls for verb in ("enable", "disable", "start", "stop", "restart"))


